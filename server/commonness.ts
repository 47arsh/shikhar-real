export function curatedCap(answer: string): TierPoints | null {
  const key = normalizeKey(answer)
  const direct = CAPS[key]
  if (direct) return direct
  if (key.endsWith('s')) {
    const singular = CAPS[key.slice(0, -1)]
    if (singular) return singular
  }
  return null
}

